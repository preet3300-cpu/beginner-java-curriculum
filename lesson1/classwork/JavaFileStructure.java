public class JavaFileStructure {
    public static void main(String[] args) {
        System.out.println("This code runs in main.");
        System.out.println("Hello world!");
        // Java programs usually start inside a class.
        // The file name and class name should match.
        System.out.println("My name is Jocelynn. I am a unicorn.");
        
    }
}
// public static void main(String[] args) start program.
// in curly braces code runs from top to bottom.