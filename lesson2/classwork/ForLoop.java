public class ForLoop {
    public static void main(String[] args) {
        for (int i = 0; i < 8; i++) {
            System.out.println("Hello world! ");
        }

        for (int i = 0; i < 5; i++) {
            System.out.println("Moo!");
        }

        for (int i = 0; i < 6; i++) {
            System.out.println("Bark!");
        }

        for (int i = 0; i < 5; i++) {
            System.out .println(i);
            
        }
    }
}