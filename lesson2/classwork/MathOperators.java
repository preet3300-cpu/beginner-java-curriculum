public class MathOperators {
    public static void main(String[] args) {
        System.out.println( 4 + 5 ); // addition adds two numbers

        System.out.println(10 - 3); 

        System.out.println(6 * 7);

        System.out.println(15 / 2); // removes the decimal point when you divide

        System.out.println(15.0 / 2); //decimal division gives decimal answer

        System.out.println(15 % 2); // modulus gives remainder percent is the symbol

        // combination of numbers and math operators is fine java follows PEMDAS
        System.out.println(2 + 3 * 4); 
        System.out.println((2 +3) * 4);

        int a = 8;
        int b = 3;
        int y = a + b;
        System.out.println("a + b = " + y);
    }
}